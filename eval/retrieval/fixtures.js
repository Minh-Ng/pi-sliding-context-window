function relevantWindow(documentId, evidence) {
  const document = documents.find(({ id }) => id === documentId);
  if (!document) throw new Error(`unknown fixture document: ${documentId}`);
  return Object.freeze({ documentId, ...locateUtf8Evidence(document.text, evidence) });
}

